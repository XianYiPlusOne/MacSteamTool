#!/usr/bin/env python3
"""Generate guarded native adapter addresses from reviewed profiles.json; no scanning."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
docs = json.loads((root/'Native/SteamIntegration/profiles.json').read_text())
names = list(docs[0]['functions']); layouts = list(docs[0]['layout'])
out = ['// Generated by script/generate_steam_profile_header.py. Review profiles.json to update.', '#pragma once', '#include <mach-o/loader.h>', '#include <cstdint>', '#include <cstring>', 'namespace RuntimeProfile {', 'struct Site { uintptr_t offset; unsigned char bytes[32]; unsigned size; };', 'struct Profile { unsigned char uuid[16]; uint64_t build;']
out += [f'    Site {n};' for n in names]+[f'    uintptr_t {n};' for n in layouts]+['};','inline const Profile profiles[] = {']
for doc in docs:
    bytearraystr=lambda s: ','.join('0x'+s[i:i+2] for i in range(0,len(s),2))
    out += ['{{'+bytearraystr(doc['uuid'])+'},'+str(doc['build'])+',']
    for n in names:
        v=doc['functions'][n];out += ['{'+v['offset']+',{'+bytearraystr(v['bytes'])+'},'+str(len(v['bytes'])//2)+'},']
    out += [','.join(doc['layout'][n] for n in layouts)+'},']
out += ['};', '''inline const Profile& Get(uintptr_t base) {
    static const Profile unsupported{};
    auto h=reinterpret_cast<const mach_header_64*>(base);
    if (!h || h->magic!=MH_MAGIC_64 || h->cputype!=CPU_TYPE_ARM64 || h->sizeofcmds>1024*1024) return unsupported;
    auto p=reinterpret_cast<const unsigned char*>(h+1),end=p+h->sizeofcmds;
    for (unsigned i=0;i<h->ncmds && p+sizeof(load_command)<=end;++i) {
        auto c=reinterpret_cast<const load_command*>(p);
        if(c->cmdsize<sizeof(*c)||c->cmdsize>static_cast<size_t>(end-p)) return unsupported;
        if(c->cmd==LC_UUID && c->cmdsize>=sizeof(uuid_command)) {
            for(const auto& profile:profiles) if(!memcmp(reinterpret_cast<const uuid_command*>(p)->uuid,profile.uuid,16))return profile;
            return unsupported;
        }
        p+=c->cmdsize;
    }
    return unsupported;
}
inline bool UUID(uintptr_t b) { return Get(b).build!=0; }
inline bool Check(uintptr_t b,const Site& site) {
    if(!site.offset || !site.size || site.size>32)return false;
    auto h=reinterpret_cast<const mach_header_64*>(b);
    auto c=reinterpret_cast<const load_command*>(h+1);
    for(unsigned i=0;i<h->ncmds;++i){
        if(c->cmd==LC_SEGMENT_64){auto s=reinterpret_cast<const segment_command_64*>(c);
            if(!strcmp(s->segname,"__TEXT") && site.offset>=s->vmaddr && site.offset+site.size<=s->vmaddr+s->vmsize)
                return !memcmp(reinterpret_cast<void*>(b+site.offset),site.bytes,site.size);
        }
        c=reinterpret_cast<const load_command*>(reinterpret_cast<const char*>(c)+c->cmdsize);
    }return false;
}''']
for n in names:out += [f'inline uintptr_t {n}(uintptr_t b) {{ return Get(b).{n}.offset; }}', f'inline bool Check_{n}(uintptr_t b) {{ return Check(b,Get(b).{n}); }}']
out+=['}']
(root/'Native/SteamIntegration/steam_profiles.h').write_text('\n'.join(out)+'\n')
